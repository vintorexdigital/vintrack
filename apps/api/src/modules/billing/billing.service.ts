import { Inject, Injectable } from '@nestjs/common';
import { and, asc, desc, eq, inArray, isNull, lt, ne, sql } from 'drizzle-orm';
import { buildInvoice, dunningAction, monthPeriod, taxRateBpsFor } from '@trackrex/rules';
import { generateInvoiceBody, planByKey, recordPaymentBody, updatePlanBody, voidInvoiceBody } from '@trackrex/schemas';
import { invoices, payments, plans, platformAuditLog, tenants, tenantUsage } from '../../core/auth/platform.tables.js';
import { TenantDirectory } from '../../core/auth/tenant-directory.service.js';
import { currentAuth, currentStore } from '../../core/context.js';
import { Db } from '../../core/database/db.service.js';
import { conflict, notFound, unprocessable } from '../../core/errors.js';

export type InvoiceRow = typeof invoices.$inferSelect;
const DUE_DAYS = 7;
const DAY = 86_400_000;

/**
 * Platform-side billing: prices, invoice generation, payments and dunning. All writes run as the platform role,
 * because invoices are the platform's records; companies only read them.
 */
@Injectable()
export class BillingService {
  constructor(private readonly db: Db, private readonly dir: TenantDirectory) {}

  private audit(action: string, tenantId: string | null, details: Record<string, unknown>, entityId?: string) {
    let actor: { id: string | null; type: 'platform_user' | 'system' } = { id: null, type: 'system' };
    let ip: string | null = null;
    let requestId: string | null = null;
    try { actor = { id: currentAuth().userId, type: 'platform_user' }; const s = currentStore(); ip = s.ip ?? null; requestId = s.requestId; } catch { /* system run */ }
    return this.db.platform.insert(platformAuditLog).values({ actorId: actor.id, actorType: actor.type, tenantId, action, entity: 'invoice', entityId: entityId ?? null, details, ip, requestId });
  }

  /* ---------- plans ---------- */

  listPlans() { return this.db.platform.select().from(plans).orderBy(asc(plans.sort)); }

  async priceFor(planKey: string, currency: string): Promise<number> {
    const [p] = await this.db.platform.select().from(plans).where(eq(plans.key, planKey));
    if (!p || !p.active) throw unprocessable('That plan is not available.', [{ path: 'planKey', message: 'Not available' }]);
    const price = p.prices[currency] ?? p.prices.INR;
    if (price === undefined) throw unprocessable(`No ${currency} price is set for this plan.`);
    return price;
  }

  async updatePlan(key: string, body: unknown) {
    const b = updatePlanBody.parse(body);
    const [before] = await this.db.platform.select().from(plans).where(eq(plans.key, key));
    if (!before) throw notFound('Plan');
    await this.db.platform.update(plans).set({ prices: b.prices, ...(b.active === undefined ? {} : { active: b.active }), updatedAt: sql`now()` }).where(eq(plans.key, key));
    await this.audit('plan.updated', null, { key, from: before.prices, to: b.prices }, key);
    return (await this.listPlans()).find((p) => p.key === key);
  }

  /* ---------- invoices ---------- */

  private async nextNumber(year: number): Promise<string> {
    const r = await this.db.platform.execute(sql`insert into platform.invoice_counters (year, last) values (${year}, 1) on conflict (year) do update set last = platform.invoice_counters.last + 1 returning last`);
    return `INV-${year}-${String((r.rows[0] as { last: number }).last).padStart(5, '0')}`;
  }

  /** One invoice per company per month, issued in advance. Calling again for the same month returns the existing one. */
  async generate(tenantId: string, rawBody: unknown = {}, now = Date.now()): Promise<InvoiceRow> {
    const { date } = generateInvoiceBody.parse(rawBody ?? {});
    const [t] = await this.db.platform.select().from(tenants).where(eq(tenants.id, tenantId));
    if (!t) throw notFound('Company');
    if (t.planKey === 'trial') throw conflict('trial_plan', 'This company is on a trial and has no plan to bill yet.');
    if (t.status === 'deleted' || t.status === 'cancelled') throw conflict('not_billable', 'This company is closed.');
    const period = monthPeriod(date ?? new Date(now).toISOString().slice(0, 10));
    const [existing] = await this.db.platform.select().from(invoices).where(and(eq(invoices.tenantId, tenantId), eq(invoices.periodStart, period.start), ne(invoices.status, 'void')));
    if (existing) return existing;
    const unit = await this.priceFor(t.planKey, t.currency);
    const plan = planByKey(t.planKey);
    const draft = buildInvoice({ planName: plan?.name ?? t.planKey, seats: t.seatLimit, unitMinor: unit, periodStart: period.start, periodEnd: period.end, taxRateBps: taxRateBpsFor(t.country) });
    const number = await this.nextNumber(Number(period.start.slice(0, 4)));
    let createdBy: string | null = null;
    try { createdBy = currentAuth().userId; } catch { /* generated by the scheduler */ }
    const [row] = await this.db.platform.insert(invoices).values({
      tenantId, number, periodStart: period.start, periodEnd: period.end, currency: t.currency, planKey: t.planKey, seats: t.seatLimit, lines: draft.lines,
      subtotalMinor: draft.subtotalMinor, taxRateBps: draft.taxRateBps, taxMinor: draft.taxMinor, totalMinor: draft.totalMinor,
      issuedAt: new Date(now).toISOString(), dueAt: new Date(now + DUE_DAYS * DAY).toISOString(), createdBy,
    }).returning();
    await this.audit('invoice.issued', tenantId, { number, totalMinor: draft.totalMinor, period }, row!.id);
    return row!;
  }

  async list(q: { tenantId?: string; status?: string; limit?: number }) {
    const limit = Math.min(Number(q.limit ?? 50), 200);
    return this.db.platform.select().from(invoices)
      .where(and(q.tenantId ? eq(invoices.tenantId, q.tenantId) : undefined, q.status ? inArray(invoices.status, q.status.split(',')) : undefined))
      .orderBy(desc(invoices.issuedAt)).limit(limit);
  }

  async get(id: string) {
    const [inv] = await this.db.platform.select().from(invoices).where(eq(invoices.id, id));
    if (!inv) throw notFound('Invoice');
    const pays = await this.db.platform.select().from(payments).where(eq(payments.invoiceId, id)).orderBy(asc(payments.receivedAt));
    return { ...inv, payments: pays };
  }

  async void(id: string, rawBody: unknown) {
    const b = voidInvoiceBody.parse(rawBody);
    const inv = await this.get(id);
    if (inv.status === 'paid') throw conflict('already_paid', 'A paid invoice cannot be voided.');
    if (inv.status === 'void') return inv;
    await this.db.platform.update(invoices).set({ status: 'void', voidReason: b.reason, updatedAt: sql`now()` }).where(eq(invoices.id, id));
    await this.audit('invoice.voided', inv.tenantId, { number: inv.number, reason: b.reason }, id);
    return this.get(id);
  }

  /** Records a payment. Partial payments accumulate; the invoice is paid once they cover the total. Redelivered provider events are ignored. */
  async recordPayment(id: string, rawBody: unknown, opts: { method?: string; providerEventId?: string; recordedBy?: string | null } = {}) {
    const b = recordPaymentBody.parse({ method: 'bank_transfer', ...(rawBody as object) });
    const inv = await this.get(id);
    if (inv.status === 'void') throw conflict('invoice_void', 'This invoice was voided.');
    if (opts.providerEventId) {
      const dup = await this.db.platform.select({ id: payments.id }).from(payments).where(eq(payments.providerEventId, opts.providerEventId));
      if (dup.length) return inv;
    }
    let by: string | null = opts.recordedBy ?? null;
    if (by === null && !opts.providerEventId) { try { by = currentAuth().userId; } catch { /* system */ } }
    await this.db.platform.insert(payments).values({ tenantId: inv.tenantId, invoiceId: id, amountMinor: b.amountMinor, currency: inv.currency, method: opts.method ?? b.method, reference: b.reference ?? null, providerEventId: opts.providerEventId ?? null, recordedBy: by });
    const [sum] = await this.db.platform.select({ n: sql<number>`coalesce(sum(${payments.amountMinor}), 0)::bigint` }).from(payments).where(eq(payments.invoiceId, id));
    const paid = Number(sum?.n ?? 0) >= inv.totalMinor;
    if (paid && inv.status !== 'paid') {
      await this.db.platform.update(invoices).set({ status: 'paid', paidAt: sql`now()`, updatedAt: sql`now()` }).where(eq(invoices.id, id));
      await this.afterPaid(inv.tenantId);
    }
    await this.audit('invoice.payment_recorded', inv.tenantId, { number: inv.number, amountMinor: b.amountMinor, method: opts.method ?? b.method, paid }, id);
    return this.get(id);
  }

  /** A paid invoice activates a trial that was subscribed, and lifts a suspension that was only for non-payment. */
  private async afterPaid(tenantId: string): Promise<void> {
    const [t] = await this.db.platform.select().from(tenants).where(eq(tenants.id, tenantId));
    if (!t) return;
    const stillOverdue = await this.db.platform.select({ id: invoices.id }).from(invoices).where(and(eq(invoices.tenantId, tenantId), eq(invoices.status, 'open'), lt(invoices.dueAt, new Date().toISOString()))).limit(1);
    let to: string | null = null;
    if (t.status === 'trial' && t.planKey !== 'trial') to = 'active';
    else if (t.status === 'past_due' && !stillOverdue.length) to = 'active';
    else if (t.status === 'suspended' && t.suspendedReason?.startsWith('Unpaid invoice') && !stillOverdue.length) to = 'active';
    if (!to) return;
    await this.db.platform.update(tenants).set({ status: to, pastDueSince: null, suspendedAt: null, suspendedReason: null, updatedAt: sql`now()` }).where(eq(tenants.id, tenantId));
    this.dir.invalidate(tenantId);
    await this.audit(`tenant.${to === 'active' ? 'activated_by_payment' : to}`, tenantId, { from: t.status });
  }

  /* ---------- scheduled work ---------- */

  /** Issue this month's invoice for every paying company that does not have one yet. */
  async runInvoicing(now = Date.now()): Promise<{ issued: number }> {
    const due = await this.db.platform.select().from(tenants).where(and(inArray(tenants.status, ['active', 'past_due']), ne(tenants.planKey, 'trial'), eq(tenants.isDemo, false)));
    let issued = 0;
    for (const t of due) {
      const period = monthPeriod(new Date(now).toISOString().slice(0, 10));
      const [have] = await this.db.platform.select({ id: invoices.id }).from(invoices).where(and(eq(invoices.tenantId, t.id), eq(invoices.periodStart, period.start), ne(invoices.status, 'void')));
      if (have) continue;
      await this.generate(t.id, {}, now);
      issued++;
    }
    return { issued };
  }

  /** Move companies with overdue invoices to past due after a week and suspend them after thirty days. */
  async runDunning(now = Date.now()): Promise<{ pastDue: number; suspended: number }> {
    const open = await this.db.platform.select().from(invoices).where(and(eq(invoices.status, 'open'), lt(invoices.dueAt, new Date(now).toISOString()))).orderBy(asc(invoices.dueAt));
    const oldest = new Map<string, InvoiceRow>();
    for (const i of open) if (!oldest.has(i.tenantId)) oldest.set(i.tenantId, i);
    const out = { pastDue: 0, suspended: 0 };
    for (const [tenantId, inv] of oldest) {
      const [t] = await this.db.platform.select().from(tenants).where(and(eq(tenants.id, tenantId), eq(tenants.isDemo, false)));
      if (!t || ['suspended', 'cancelled', 'deleted'].includes(t.status)) continue;
      const action = dunningAction(Math.floor((now - new Date(inv.dueAt).getTime()) / DAY));
      if (action === 'suspend') {
        await this.db.platform.update(tenants).set({ status: 'suspended', suspendedAt: sql`now()`, suspendedReason: `Unpaid invoice ${inv.number}`, updatedAt: sql`now()` }).where(eq(tenants.id, tenantId));
        this.dir.invalidate(tenantId);
        await this.audit('tenant.suspended_for_non_payment', tenantId, { invoice: inv.number }, inv.id);
        out.suspended++;
      } else if (action === 'past_due' && t.status !== 'past_due') {
        await this.db.platform.update(tenants).set({ status: 'past_due', pastDueSince: inv.dueAt, updatedAt: sql`now()` }).where(eq(tenants.id, tenantId));
        this.dir.invalidate(tenantId);
        await this.audit('tenant.past_due', tenantId, { invoice: inv.number }, inv.id);
        out.pastDue++;
      }
    }
    return out;
  }

  /** Recurring revenue is seats times price for companies that are paying or in arrears; trials and demos are excluded. */
  async overview() {
    const rows = await this.db.platform.select({ planKey: tenants.planKey, currency: tenants.currency, status: tenants.status, seats: tenants.seatLimit, used: tenantUsage.employeesActive })
      .from(tenants).leftJoin(tenantUsage, eq(tenantUsage.tenantId, tenants.id)).where(and(inArray(tenants.status, ['active', 'past_due']), eq(tenants.isDemo, false), isNull(tenants.deletedAt)));
    const prices = new Map((await this.listPlans()).map((p) => [p.key, p.prices]));
    const mrr: Record<string, number> = {};
    for (const r of rows) {
      const price = prices.get(r.planKey)?.[r.currency] ?? prices.get(r.planKey)?.INR ?? 0;
      mrr[r.currency] = (mrr[r.currency] ?? 0) + price * r.seats;
    }
    const outstanding = await this.db.platform.select({ currency: invoices.currency, n: sql<number>`count(*)::int`, total: sql<number>`coalesce(sum(${invoices.totalMinor}),0)::bigint`, overdue: sql<number>`count(*) filter (where ${invoices.dueAt} < now())::int` })
      .from(invoices).where(eq(invoices.status, 'open')).groupBy(invoices.currency);
    return { mrrMinor: mrr, payingCompanies: rows.length, outstanding: outstanding.map((o) => ({ currency: o.currency, invoices: o.n, totalMinor: Number(o.total), overdue: o.overdue })) };
  }
}
