import { scale, semanticDark, semanticHighContrast, semanticLight, statusKeys, type SemanticTokens } from './tokens.js';

const block = (selector: string, t: SemanticTokens) =>
  `${selector} {\n${Object.entries(t).map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}\n`;

/** Derived status tints (14% over the surface) so register cells never rely on colour alone. */
const tints = (): SemanticTokens =>
  Object.fromEntries(
    statusKeys.map((k) => [`status-${k}-tint`, `color-mix(in srgb, var(--status-${k}) 14%, var(--color-surface))`]),
  );

export function toCss(): string {
  return [
    '/* Generated by packages/tokens/scripts/build.mjs. Do not edit. */',
    block(':root', { ...scale, ...semanticLight, ...tints() }),
    '@media (prefers-color-scheme: dark) {\n' + block('  :root:not([data-theme="light"]):not([data-theme="contrast"])', semanticDark).replace(/^/gm, '') + '}\n',
    block(':root[data-theme="dark"]', semanticDark),
    block(':root[data-theme="contrast"]', semanticHighContrast),
    `@media (prefers-reduced-motion: reduce) {\n  :root { --motion-fast: 0ms; --motion-base: 0ms; }\n}\n`,
  ].join('\n');
}

/** Tailwind v4 theme: utilities (bg-canvas, text-ink, border-rule, bg-brand...) map onto the CSS variables. */
export function toTailwindTheme(): string {
  const colors: [string, string][] = [
    ['canvas', 'color-canvas'], ['surface', 'color-surface'], ['rule', 'color-rule'], ['ink', 'color-ink'],
    ['muted', 'color-muted'], ['live', 'color-live'], ['on-live', 'color-on-live'], ['brand', 'brand-primary'],
    ['brand-hover', 'brand-primary-hover'], ['brand-active', 'brand-primary-active'], ['on-brand', 'brand-on-primary'],
    ...statusKeys.flatMap((k): [string, string][] => [[k, `status-${k}`], [`${k}-tint`, `status-${k}-tint`]]),
  ];
  return [
    '/* Generated by packages/tokens/scripts/build.mjs. Do not edit. */',
    '@theme inline {',
    ...colors.map(([n, v]) => `  --color-${n}: var(--${v});`),
    '  --font-sans: var(--font-sans);',
    '  --radius-input: var(--radius-input);',
    '  --radius-button: var(--radius-button);',
    '  --radius-overlay: var(--radius-overlay);',
    '}',
    '',
  ].join('\n');
}

/** React Native theme object source (consumed by apps/mobile). */
export function toNativeTheme(): string {
  const pick = (t: SemanticTokens) => JSON.stringify(Object.fromEntries(Object.entries(t).filter(([k]) => !k.startsWith('shadow'))), null, 2);
  return `// Generated by packages/tokens/scripts/build.mjs. Do not edit.\nexport const light = ${pick(semanticLight)} as const;\nexport const dark = ${pick(semanticDark)} as const;\nexport const highContrast = ${pick(semanticHighContrast)} as const;\n`;
}
